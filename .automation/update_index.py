#!/usr/bin/env python3
"""Regenerate everything that can be derived, so humans and the daily agent don't hand-edit it.

  python3 .automation/update_index.py [--today YYYY-MM-DD]

What it does:
  1. README.md  <!-- CATEGORIES -->  grouped category tables, from .automation/categories.json
  2. README.md  <!-- BADGES -->      last-updated date (latest digest) and edition count
  3. <group>/README.md                group index pages (except groups marked "hub": true)
  4. daily/README.md <!-- INDEX -->  list of all digests, newest first
                                     (uses an optional `<!-- summary: ... -->` line in each digest)
  5. 🆕 expiry                         removes 🆕 from headings whose "Added: YYYY-MM-DD" is more than 7 days old
  6. feed.xml                         Atom feed of the latest digests, so readers can subscribe

Today defaults to the current date in Australia/Brisbane.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
from pathlib import Path
from xml.sax.saxutils import escape
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parent.parent
REG = json.loads((ROOT / ".automation" / "categories.json").read_text(encoding="utf-8"))
NEW_DAYS = 7
REPO_URL = "https://github.com/lmquanacs/ai-engineering"
FEED_ENTRIES = 30


def replace_block(text: str, name: str, body: str) -> str:
    pattern = re.compile(rf"(<!-- {name}:START -->\n)(.*?)(<!-- {name}:END -->)", re.S)
    if not pattern.search(text):
        raise SystemExit(f"marker {name} not found")
    return pattern.sub(lambda m: m.group(1) + body.rstrip() + "\n" + m.group(3), text)


def rel_link(md_text: str, prefix: str) -> str:
    """Re-root repo-relative links in a summary for a page living under `prefix`."""
    if not prefix:
        return md_text
    def fix(m: re.Match) -> str:
        target = m.group(2)
        if target.startswith(("http", "#")):
            return m.group(0)
        rel = os.path.relpath(target, prefix) + ("/" if target.endswith("/") else "")
        return f"{m.group(1)}{rel})"

    return re.sub(r"(\[[^\]]*\]\()([^)]+)\)", fix, md_text)


def cadence_label(c: dict) -> str:
    return "daily" if c["cadence"] == "daily" else "weekly (Mon)"


def category_table(group: dict, prefix: str = "") -> str:
    rows = ["| Category | What you'll find | Best for | Checked |", "|---|---|---|---|"]
    for c in group["categories"]:
        link = rel_link(f"[**{c['title']}**]({c['path']}/README.md)", prefix)
        rows.append(f"| {link} | {rel_link(c['summary'], prefix)} | {c['best_for']} | {cadence_label(c)} |")
    return "\n".join(rows)


def render_readme_categories() -> str:
    out = []
    for g in REG["groups"]:
        out.append(f"### {g['emoji']} {g['title']}\n")
        out.append(g["intro"] + "\n")
        out.append(category_table(g) + "\n")
    return "\n".join(out)


def render_group_page(g: dict) -> str:
    return (
        f"# {g['emoji']} {g['title']}\n\n"
        f"<!-- Generated by .automation/update_index.py from categories.json. Do not edit by hand. -->\n\n"
        f"← [Repo home](../README.md)\n\n"
        f"{rel_link(g['intro'], g['path'])}\n\n"
        f"{category_table(g, g['path'])}\n"
    )


def digests() -> list[tuple[dt.date, Path]]:
    found = []
    for p in (ROOT / "daily").glob("*/*/*.md"):
        try:
            found.append((dt.date.fromisoformat(p.stem), p))
        except ValueError:
            continue
    return sorted(found, reverse=True)


def render_daily_index(items: list[tuple[dt.date, Path]]) -> str:
    out, year, month = [], None, None
    for d, p in items:
        if d.year != year:
            year, month = d.year, None
            out.append(f"## {year}\n")
        if d.month != month:
            month = d.month
            out.append(f"### {d.strftime('%B')}\n")
        m = re.search(r"<!-- summary: (.*?) -->", p.read_text(encoding="utf-8"))
        summary = f": {m.group(1)}" if m else ""
        out.append(f"- [{d.strftime('%a %d %b %Y')}]({p.relative_to(ROOT / 'daily').as_posix()}){summary}")
    return "\n".join(out).strip() + "\n"


def digest_tldr(text: str) -> str:
    """The TL;DR section of a digest, as plain markdown text."""
    m = re.search(r"^## TL;DR\n(.*?)(?=^---|^## )", text, re.S | re.M)
    return m.group(1).strip() if m else ""


def render_feed(items: list[tuple[dt.date, Path]]) -> str:
    """Atom feed of the newest digests. Deterministic: depends only on the digest files."""
    entries = []
    for d, p in items[:FEED_ENTRIES]:
        text = p.read_text(encoding="utf-8")
        m = re.search(r"<!-- summary: (.*?) -->", text)
        summary = m.group(1) if m else ""
        url = f"{REPO_URL}/blob/main/{p.relative_to(ROOT).as_posix()}"
        stamp = f"{d.isoformat()}T09:00:00+10:00"
        body = digest_tldr(text) or summary
        entries.append(
            "  <entry>\n"
            f"    <title>{escape('Daily digest · ' + d.strftime('%a %d %b %Y'))}</title>\n"
            f'    <link href="{escape(url)}"/>\n'
            f"    <id>{escape(url)}</id>\n"
            f"    <updated>{stamp}</updated>\n"
            f"    <summary>{escape(summary)}</summary>\n"
            f'    <content type="text">{escape(body)}</content>\n'
            "  </entry>"
        )
    updated = f"{items[0][0].isoformat()}T09:00:00+10:00" if items else "1970-01-01T00:00:00Z"
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by .automation/update_index.py. Do not edit by hand. -->\n"
        '<feed xmlns="http://www.w3.org/2005/Atom">\n'
        "  <title>AI Engineering Utilities · daily digest</title>\n"
        "  <subtitle>What changed today for engineers building with AI: tools, models, prices, security.</subtitle>\n"
        f'  <link href="{REPO_URL}"/>\n'
        f'  <link rel="self" href="https://raw.githubusercontent.com/lmquanacs/ai-engineering/main/feed.xml"/>\n'
        f"  <id>{REPO_URL}</id>\n"
        f"  <updated>{updated}</updated>\n"
        "  <author><name>lmquanacs</name></author>\n"
        + "\n".join(entries)
        + "\n</feed>\n"
    )


def expire_new_markers(today: dt.date) -> int:
    changed = 0
    cutoff = today - dt.timedelta(days=NEW_DAYS)
    for md in ROOT.rglob("*.md"):
        if ".git" in md.parts or "daily" in md.parts:
            continue
        lines = md.read_text(encoding="utf-8").split("\n")
        dirty = False
        for i, line in enumerate(lines):
            if not (line.startswith("#") and "🆕" in line):
                continue
            for nxt in lines[i + 1:]:
                if nxt.startswith("#"):
                    break
                m = re.search(r"Added: (\d{4}-\d{2}-\d{2})", nxt)
                if m:
                    if dt.date.fromisoformat(m.group(1)) < cutoff:
                        lines[i] = line.replace(" 🆕", "").replace("🆕", "")
                        dirty = True
                        changed += 1
                    break
        if dirty:
            md.write_text("\n".join(lines), encoding="utf-8")
    return changed


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--today", help="YYYY-MM-DD (default: today in Australia/Brisbane)")
    args = ap.parse_args()
    today = dt.date.fromisoformat(args.today) if args.today else dt.datetime.now(ZoneInfo("Australia/Brisbane")).date()

    items = digests()
    readme_p = ROOT / "README.md"
    readme = readme_p.read_text(encoding="utf-8")
    readme = replace_block(readme, "CATEGORIES", render_readme_categories())
    if items:
        last = items[0][0].isoformat().replace("-", "--")
        badges = (
            f"![Last updated](https://img.shields.io/badge/last%20updated-{last}-2563eb)\n"
            "![Schedule](https://img.shields.io/badge/updates-daily%20~9am%20Brisbane-16a34a)\n"
            f"![Editions](https://img.shields.io/badge/daily%20editions-{len(items)}-9333ea)"
        )
        readme = replace_block(readme, "BADGES", badges)
    readme_p.write_text(readme, encoding="utf-8")

    for g in REG["groups"]:
        if g.get("hub"):
            continue
        (ROOT / g["path"]).mkdir(parents=True, exist_ok=True)
        (ROOT / g["path"] / "README.md").write_text(render_group_page(g), encoding="utf-8")

    daily_p = ROOT / "daily" / "README.md"
    daily_p.write_text(replace_block(daily_p.read_text(encoding="utf-8"), "INDEX", render_daily_index(items)), encoding="utf-8")

    (ROOT / "feed.xml").write_text(render_feed(items), encoding="utf-8")

    expired = expire_new_markers(today)
    print(f"OK: README, {sum(1 for g in REG['groups'] if not g.get('hub'))} group pages, {len(items)} digests indexed, feed.xml, {expired} 🆕 markers expired (today={today})")


if __name__ == "__main__":
    main()
